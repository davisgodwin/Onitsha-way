"""
ONITSHA WAY — original club mixes (v0.50).

Two continuous DJ mixes for the nightclubs, composed and synthesised here from scratch (NumPy + FFmpeg):
  * "Onitsha Nights" — an Afrobeats DJ mix: four original tracks at 104 BPM blended with 8-bar crossfades,
    talking-drum fills, highlife guitar, synth leads, risers and a DJ air horn.
  * "Amapiano Sunday" — an amapiano mixtape: four original tracks at 113 BPM with the log drum, shakers, jazzy
    piano chords, pads and flute-like leads.
No samples, no vocals, no covers, no melodies from any existing song: every note is generated by the rules below.
Run:  python3 scripts/compose-club-mixes.py    (writes public/audio/club/*.mp3; deterministic)
"""
import numpy as np, wave, subprocess, sys
from pathlib import Path

SR = 32000
OUT = Path(__file__).resolve().parents[1] / 'public/audio/club'
OUT.mkdir(parents=True, exist_ok=True)

def midi(n): return 440.0 * 2 ** ((n - 69) / 12)

class Track:
    def __init__(self, bpm, bars, seed):
        self.bpm, self.bars, self.beat = bpm, bars, 60.0 / bpm
        self.n = int(bars * 4 * self.beat * SR) + SR * 2
        self.dry = np.zeros((self.n, 2)); self.wet = np.zeros((self.n, 2))
        self.rng = np.random.default_rng(seed)
    def t(self, bar, step=0.0): return (bar * 16 + step) * self.beat / 4
    def put(self, t, s, amp=1.0, pan=0.0, wet=0.0):
        i = int(t * SR)
        if i >= self.n or i < 0: return
        s = np.asarray(s) * amp; n = min(len(s), self.n - i)
        g = np.array([np.sqrt((1 - pan) / 2), np.sqrt((1 + pan) / 2)])
        a = s[:n, None] * g
        self.dry[i:i + n] += a * (1 - wet * 0.5)
        if wet: self.wet[i:i + n] += a * wet

# ---------------------------------------------------------------- instruments
def env(n, a=0.004, d=6.0):
    x = np.arange(n) / SR
    return np.minimum(1, x / a) * np.exp(-x * d), x

def kick(amp=1.0, tight=1.0):
    n = int(0.32 * SR); e, x = env(n, 0.001, 9 * tight)
    ph = 2 * np.pi * (48 * x + 140 * (1 - np.exp(-x * 30)) / 30)
    click = np.exp(-x * 400) * 0.4
    return (np.sin(ph) * e + click * np.sin(2 * np.pi * 1800 * x)) * amp

def noise(rng, n): return rng.normal(0, 1, n)

def hp(s):  # crude high-pass
    return s - np.convolve(s, np.ones(6) / 6, mode='same')

def lp(s, k=8):
    return np.convolve(s, np.ones(k) / k, mode='same')

def clap(rng, amp=1.0):
    n = int(0.22 * SR); x = np.arange(n) / SR; s = np.zeros(n)
    for k, off in enumerate([0, 0.011, 0.023]):
        i = int(off * SR); m = n - i; xx = np.arange(m) / SR
        s[i:] += hp(noise(rng, m)) * np.exp(-xx * (60 if k < 2 else 22))
    return s * 0.24 * amp + np.sin(2 * np.pi * 210 * x) * np.exp(-x * 40) * 0.12 * amp

def rim(rng, amp=1.0):
    n = int(0.08 * SR); x = np.arange(n) / SR
    return (np.sin(2 * np.pi * 900 * x) * 0.5 + np.sin(2 * np.pi * 1450 * x) * 0.3 + hp(noise(rng, n)) * 0.25) * np.exp(-x * 90) * 0.3 * amp

def shaker(rng, amp=1.0, length=0.07):
    n = int(length * SR); x = np.arange(n) / SR
    return hp(hp(noise(rng, n))) * np.minimum(1, x / 0.006) * np.exp(-x * 55) * 0.05 * amp

def hat(rng, amp=1.0, open_=False):
    n = int((0.28 if open_ else 0.05) * SR); x = np.arange(n) / SR
    return hp(hp(hp(noise(rng, n)))) * np.exp(-x * (14 if open_ else 110)) * 0.045 * amp

def talking_drum(note, glide, amp=1.0, length=0.22):
    n = int(length * SR); x = np.arange(n) / SR
    f = midi(note) * 2 ** (glide * np.minimum(1, x / length) / 12)
    ph = 2 * np.pi * np.cumsum(f) / SR
    return (np.sin(ph) + 0.25 * np.sin(2 * ph)) * np.minimum(1, x / 0.003) * np.exp(-x * 10) * 0.3 * amp

def conga(note, amp=1.0):
    n = int(0.2 * SR); x = np.arange(n) / SR
    f = midi(note) * (1 + 0.25 * np.exp(-x * 40)); ph = 2 * np.pi * np.cumsum(f) / SR
    return np.sin(ph) * np.exp(-x * 22) * 0.28 * amp

def woodblock(amp=1.0):
    n = int(0.06 * SR); x = np.arange(n) / SR
    return (np.sin(2 * np.pi * 1180 * x) + 0.4 * np.sin(2 * np.pi * 2650 * x)) * np.exp(-x * 75) * 0.18 * amp

def log_drum(note, length, amp=1.0, bend=7):
    """The amapiano log drum: a round, pitched, slightly distorted thump that slides into its note."""
    n = int(length * SR); x = np.arange(n) / SR
    f = midi(note) * 2 ** (bend * np.exp(-x * 45) / 12); ph = 2 * np.pi * np.cumsum(f) / SR
    s = np.sin(ph) + 0.35 * np.sin(2 * ph + 0.3) + 0.12 * np.sin(3 * ph)
    s = np.tanh(s * 2.2) * np.minimum(1, x / 0.004) * np.exp(-x * (3.0 / max(0.15, length)))
    return s * 0.42 * amp

def bass(note, length, amp=1.0):
    n = int(length * SR); x = np.arange(n) / SR; f = midi(note)
    s = np.sin(2 * np.pi * f * x) + 0.3 * np.sin(4 * np.pi * f * x) + 0.1 * np.sin(6 * np.pi * f * x)
    return s * np.minimum(1, x / 0.01) * np.minimum(1, np.maximum(0, (length - x) / 0.03)) * np.exp(-x * 1.5) * 0.26 * amp

def piano(note, length, amp=1.0):
    n = int(max(length, 0.6) * SR); x = np.arange(n) / SR; f = midi(note)
    s = sum(np.sin(2 * np.pi * f * k * x * (1 + 0.0004 * k * k)) * (0.6 ** (k - 1)) * np.exp(-x * (2.2 + k * 0.9)) for k in range(1, 7))
    return s * np.minimum(1, x / 0.003) * 0.23 * amp

def guitar(note, amp=1.0):
    n = int(0.3 * SR); x = np.arange(n) / SR; f = midi(note)
    s = sum(np.sin(2 * np.pi * f * k * x) / k ** 1.3 for k in range(1, 8)) * np.exp(-x * 13)
    return s * np.minimum(1, x / 0.002) * 0.17 * amp

def pad(notes, length, amp=1.0):
    n = int(length * SR); x = np.arange(n) / SR; s = np.zeros(n)
    for note in notes:
        for det in (-0.08, 0.0, 0.09):
            f = midi(note + det); s += ((2 * ((f * x) % 1) - 1) * 0.5)
    s = lp(lp(s, 24), 24)
    a = np.minimum(1, x / 0.6) * np.minimum(1, np.maximum(0, (length - x) / 0.8))
    return s * a * 0.035 * amp

def lead(note, length, amp=1.0, kind='synth'):
    n = int(length * SR); x = np.arange(n) / SR; f = midi(note) * (1 + 0.004 * np.sin(2 * np.pi * 5.5 * x) * np.minimum(1, x / 0.2))
    ph = 2 * np.pi * np.cumsum(f) / SR
    if kind == 'flute':
        s = np.sin(ph) + 0.08 * np.sin(2 * ph) + 0.03 * noise(np.random.default_rng(int(note * 7)), n)
        a = np.minimum(1, x / 0.06) * np.minimum(1, np.maximum(0, (length - x) / 0.08))
    else:
        s = np.sign(np.sin(ph)) * 0.4 + np.sin(ph) * 0.6; s = lp(s, 5)
        a = np.minimum(1, x / 0.01) * np.exp(-x * 1.4)
    return s * a * 0.13 * amp

def riser(rng, length, amp=1.0):
    n = int(length * SR); x = np.arange(n) / SR; s = hp(noise(rng, n))
    return s * (x / length) ** 2.2 * 0.18 * amp

def air_horn(amp=1.0):
    # the DJ horn: a bright stacked tone in a short-short-long pattern
    out = []
    for length, gap in ((0.16, 0.06), (0.16, 0.06), (0.55, 0)):
        n = int(length * SR); x = np.arange(n) / SR; s = np.zeros(n)
        for f in (311, 392, 466, 622):
            s += (2 * ((f * x) % 1) - 1) * 0.25
        s = np.tanh(s * 1.5) * np.minimum(1, x / 0.01) * np.minimum(1, (length - x) / 0.03 + 0.001)
        out.append(s); out.append(np.zeros(int(gap * SR)))
    return np.concatenate(out) * 0.22 * amp

def reverb(sig, seconds=1.4, seed=7):
    rng = np.random.default_rng(seed); n = int(seconds * SR); x = np.arange(n) / SR
    ir = rng.normal(0, 1, (n, 2)) * np.exp(-x * 4.2)[:, None]; ir[:, 0] = lp(ir[:, 0], 3); ir[:, 1] = lp(ir[:, 1], 3)
    L = len(sig) + n; N = 1 << (L - 1).bit_length(); out = np.zeros((len(sig), 2))
    for c in range(2):
        out[:, c] = np.fft.irfft(np.fft.rfft(sig[:, c], N) * np.fft.rfft(ir[:, c], N), N)[:len(sig)]
    return out / (np.max(np.abs(out)) + 1e-9) * np.max(np.abs(sig)) * 0.55

# ---------------------------------------------------------------- music theory
MINOR_PENT = [0, 3, 5, 7, 10]
def chord(root, quality):
    return [root + i for i in {'m7': [0, 3, 7, 10], 'm9': [0, 3, 7, 10, 14], 'maj7': [0, 4, 7, 11], 'maj9': [0, 4, 7, 11, 14], '7': [0, 4, 7, 10], 'sus': [0, 5, 7, 10]}[quality]]

# ---------------------------------------------------------------- Afrobeats
def afrobeats(seed, key, prog, bars=56):
    tr = Track(104, bars, seed); rng = tr.rng
    kicks = [[0, 7, 10], [0, 6, 10, 13], [0, 7, 8, 14]][seed % 3]
    rims = [3, 6, 10, 12, 15] if seed % 2 else [3, 7, 10, 12]
    lead_phrase = [(rng.integers(0, 16), MINOR_PENT[rng.integers(0, 5)] + 12 * rng.integers(0, 2)) for _ in range(6)]
    gtr_steps = [[2, 5, 8, 11, 14], [1, 4, 6, 9, 12, 14], [2, 6, 7, 10, 14]][seed % 3]
    for bar in range(bars):
        sec = 'intro' if bar < 8 else 'a' if bar < 24 else 'break' if bar < 32 else 'b' if bar < 48 else 'outro'
        root = key + prog[(bar // 2) % len(prog)][0]; q = prog[(bar // 2) % len(prog)][1]; ch = chord(root, q)
        for st in range(16):
            t = tr.t(bar, st) + (tr.beat * 0.03 if st % 2 else 0)  # a little swing
            tr.put(t, shaker(rng, 0.7 if st % 2 else 1.0), 1, -0.45)
            if st % 2 == 0 and sec != 'intro': tr.put(t, hat(rng, 0.8 if st % 4 else 1.1), 1, 0.4)
            if sec in ('a', 'b', 'outro') and st in kicks: tr.put(t, kick(1.0), 1)
            if sec != 'intro' and st in (4, 12): tr.put(t, clap(rng, 0.9), 1, 0.05, 0.25)
            if sec in ('a', 'b') and st in rims: tr.put(t, rim(rng, 0.8), 1, 0.2)
            if st in (3, 9, 14) and sec != 'break': tr.put(t, conga(62 + (st % 5), 0.9), 1, -0.3)
            if sec in ('a', 'b', 'outro') and st in (0, 3, 6, 10, 14): tr.put(t, bass(root - 12 + (7 if st == 10 else 0), tr.beat * 0.6), 1)
            if sec in ('a', 'b') and st in gtr_steps:
                for j, nn in enumerate(ch[:3]): tr.put(t + j * 0.006, guitar(nn + 24, 0.9), 1, -0.35, 0.15)
        if bar % 8 == 7 and sec != 'break':  # talking drum fill
            for k, (st, gl) in enumerate([(8, 5), (10, -4), (11, 3), (13, 7), (14, -5), (15, 6)]):
                tr.put(tr.t(bar, st), talking_drum(57 + (k % 3) * 2, gl), 1, 0.25)
        if sec in ('break', 'a', 'b') and bar % 2 == 0: tr.put(tr.t(bar), pad([n + 12 for n in ch], tr.beat * 8), 1, 0, 0.6)
        if sec == 'break':
            for st in (0, 6, 10): tr.put(tr.t(bar, st), piano(ch[0] + 24, 0.8) + 0, 1, 0.2, 0.5)
            if bar == 31: tr.put(tr.t(bar - 3), riser(rng, tr.beat * 16), 1, 0)
        if sec == 'b':
            for st, deg in lead_phrase:
                tr.put(tr.t(bar, int(st)), lead(key + 24 + deg + (0 if bar % 4 < 2 else 2), tr.beat * 0.8), 1, 0.1, 0.35)
        if bar in (8, 32): tr.put(tr.t(bar), air_horn(), 1, 0, 0.3)
    return tr

# ---------------------------------------------------------------- Amapiano
def amapiano(seed, key, prog, bars=56):
    tr = Track(113, bars, seed); rng = tr.rng
    logs = [[(0, 0, 0.5), (3, 7, 0.3), (6, 0, 0.4), (10, 10, 0.3), (12, 7, 0.5)], [(0, 0, 0.6), (4, 12, 0.25), (7, 7, 0.3), (10, 0, 0.4), (13, 10, 0.3)], [(2, 0, 0.4), (6, 7, 0.3), (8, 0, 0.6), (11, 12, 0.25), (14, 10, 0.3)]][seed % 3]
    melody = [(rng.integers(0, 8) * 2, MINOR_PENT[rng.integers(0, 5)]) for _ in range(4)]
    for bar in range(bars):
        sec = 'intro' if bar < 8 else 'a' if bar < 24 else 'break' if bar < 32 else 'b' if bar < 48 else 'outro'
        root = key + prog[(bar // 2) % len(prog)][0]; ch = chord(root, prog[(bar // 2) % len(prog)][1])
        for st in range(16):
            t = tr.t(bar, st) + (tr.beat * 0.045 if st % 2 else 0)  # amapiano's lazy swing
            tr.put(t, shaker(rng, 1.0 if st % 4 == 2 else 0.65, 0.09), 1, -0.5)
            if st % 4 == 2 and sec != 'intro': tr.put(t, hat(rng, 0.9), 1, 0.45)
            if sec in ('a', 'b', 'outro') and st in (0, 8): tr.put(t, kick(0.85, 1.4), 1)
            if sec != 'intro' and st in (4, 12): tr.put(t, rim(rng, 1.0), 1, 0.15, 0.3)
            if sec in ('a', 'b') and st == 12: tr.put(t, clap(rng, 0.7), 1, -0.05, 0.4)
            if st in (5, 13) and sec != 'break': tr.put(t, woodblock(0.8), 1, 0.35)
            if sec in ('a', 'b', 'outro') and st == 15 and bar % 2: tr.put(t, hat(rng, 0.6, True), 1, 0.3)
        if sec in ('a', 'b'):
            for st, off, ln in logs:
                tr.put(tr.t(bar, st), log_drum(root - 12 + off, tr.beat * ln * 4), 1, 0, 0.1)
        # jazzy piano on the off-beats, and the pad
        if sec != 'intro' or bar >= 4:
            for st in ((2, 6, 11) if bar % 2 == 0 else (3, 8, 14)):
                for j, nn in enumerate(ch): tr.put(tr.t(bar, st) + j * 0.004, piano(nn + 12, 0.5, 0.75), 1, 0.25, 0.5)
        if bar % 2 == 0: tr.put(tr.t(bar), pad([n + 12 for n in ch[:4]], tr.beat * 8, 1.3), 1, 0, 0.7)
        if sec in ('break', 'b') and bar % 4 < 3:
            for st, deg in melody: tr.put(tr.t(bar, int(st)), lead(key + 24 + deg, tr.beat * 1.4, 1.1, 'flute'), 1, -0.15, 0.6)
        if sec == 'break' and bar == 31: tr.put(tr.t(bar - 3), riser(rng, tr.beat * 16, 0.8), 1, 0)
        if bar % 8 == 7 and sec in ('a', 'b'):
            for k, st in enumerate((10, 12, 13, 14, 15)): tr.put(tr.t(bar, st), log_drum(root - 12 + (k * 2) % 12, tr.beat * 0.4, 0.9, 12), 1)
    return tr

def render(tr):
    out = tr.dry + reverb(tr.wet, 1.6, int(tr.bpm))
    return out

def mix(tracks, overlap_bars=8):
    parts = [render(t) for t in tracks]; bpm = tracks[0].bpm; ov = int(overlap_bars * 4 * 60 / bpm * SR)
    lens = [int(t.bars * 4 * t.beat * SR) for t in tracks]
    total = sum(lens) - ov * (len(tracks) - 1) + SR * 2; out = np.zeros((total, 2)); pos = 0
    for k, (p, L) in enumerate(zip(parts, lens)):
        seg = p[:L + SR].copy(); n = len(seg)
        if k > 0: seg[:ov] *= np.linspace(0, 1, ov)[:, None] ** 0.7     # bring the new track in
        if k < len(parts) - 1: seg[L - ov:L] *= np.linspace(1, 0, ov)[:, None] ** 0.7; seg[L:] = 0  # and the old one out
        out[pos:pos + n] += seg[:max(0, min(n, total - pos))]
        pos += L - ov
    return out[:pos + ov]

def master(a):
    a = a - np.mean(a, axis=0)
    a = np.tanh(a * 1.05 / (np.percentile(np.abs(a), 99.9) + 1e-9)) * 0.9
    return a / max(1e-9, np.max(np.abs(a))) * 0.92

def write(name, audio):
    wav = OUT / (name + '.wav')
    with wave.open(str(wav), 'wb') as f:
        f.setnchannels(2); f.setsampwidth(2); f.setframerate(SR); f.writeframes((audio * 32767).astype('<i2').tobytes())
    subprocess.run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', '-i', str(wav), '-codec:a', 'libmp3lame', '-b:a', '128k', str(OUT / (name + '.mp3'))], check=True)
    wav.unlink(); print(name, round(len(audio) / SR, 1), 's', flush=True)

